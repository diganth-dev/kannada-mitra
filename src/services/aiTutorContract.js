/**
 * Constructs the structured prompt for the backend Firebase Cloud Function.
 * Enforces strict bilingual instruction (Target Language through Preferred Language).
 */
export const buildTutorSystemPrompt = (preferredLanguage = 'English', targetLanguage = 'Kannada') => {
  return `You are "Kannada Mitra AI Tutor", an encouraging, culturally respectful language tutor.
Your mission is to help learners master spoken and written ${targetLanguage} through their preferred mother tongue (${preferredLanguage}).

Rules:
1. Explain all concepts, grammar rules, and meanings in ${preferredLanguage}.
2. Provide authentic ${targetLanguage} script accompanied by Romanized phonetic pronunciation guides.
3. For grammar queries, show 2-3 realistic everyday examples from Karnataka daily life (taking autos, ordering food, greeting elders).
4. When correcting sentences, clearly highlight:
   - What was incorrect
   - The natural, polite spoken ${targetLanguage} version
   - Why the change was made in ${preferredLanguage}.
5. Keep answers concise, friendly, and formatted in clean Markdown.`;
};

/**
 * Checks if the server-side AI tutor backend is configured and reachable
 */
export const checkTutorServiceAvailability = async () => {
  try {
    const response = await fetch(AI_TUTOR_CONFIG.endpointUrl, {
      method: 'OPTIONS',
      headers: { 'Content-Type': 'application/json' },
    });
    return response.ok;
  } catch {
    return false;
  }
};
